/**
 * Data model for Painel do Mestre.
 *
 * Every record is an entity linked by id (section 3 of the spec).
 * UI text and seed content are pt-BR; code/identifiers are English.
 */

export type Uuid = string;
/** ISO-8601 timestamp string. */
export type IsoDateTime = string;

/** Fields shared by every stored record. */
export interface BaseEntity {
  id: Uuid;
  createdAt: IsoDateTime;
  updatedAt: IsoDateTime;
  tags: string[];
  /** Free markdown owned by the Keeper. */
  notes: string;
}

/** Provenance fields used by the importer (section 6.1). */
export interface ImportableFields {
  aliases?: string[];
  /** Stable slug so re-importing updates instead of duplicating. */
  externalKey?: string;
  source?: { batchId: Uuid; label: string; pageRef?: string };
  /** Pending items the source text did not provide, e.g. 'leitura', 'agenda', 'pino'. */
  pending?: string[];
  /** Fields that were generated by AI (prompt/mode B), e.g. 'readAloud'. */
  generatedByAI?: string[];
}

/* ------------------------------------------------------------------ Time */

export type DayPeriod = 'manha' | 'tarde' | 'noite' | 'madrugada';

/* ------------------------------------------------------------------ Map */

export interface MapEntity extends BaseEntity {
  name: string;
  /** Reference to a stored image blob. */
  imageBlobId?: Uuid;
  width: number;
  height: number;
  /** city -> district -> building floor plan. */
  parentMapId?: Uuid;
  scaleNote?: string;
}

/* ------------------------------------------------------------------ Location */

export type PointGeometry = { type: 'point'; x: number; y: number };
export type PolygonGeometry = { type: 'polygon'; points: Array<{ x: number; y: number }> };
export type Geometry = PointGeometry | PolygonGeometry;

/**
 * Read-aloud variants (section 5.1). The app picks the most specific
 * available, with fallback cascade down to `generico`.
 */
export interface ReadAloudVariants {
  primeiraVisita?: string;
  retorno?: string;
  dia?: string;
  noite?: string;
  chuva?: string;
  generico?: string;
}

export type LocationKind =
  | 'casa'
  | 'loja'
  | 'igreja'
  | 'porto'
  | 'cena-de-crime'
  | 'distrito'
  | 'armazem'
  | 'taverna'
  | 'instituicao'
  | 'outro';

export interface LocationEntity extends BaseEntity, ImportableFields {
  name: string;
  mapId: Uuid;
  geometry: Geometry;
  kind: LocationKind;
  district?: string;
  /** building -> rooms. */
  parentLocationId?: Uuid;
  baseDescription: string;
  readAloud: ReadAloudVariants;
  sensoryDetails: string[];
  /** Link to an interior floor-plan map. */
  childMapId?: Uuid;
  /** Visibility for players (fog of war). */
  discovered: boolean;
  iconKey: string;
}

/* ------------------------------------------------------------------ NPC */

export type NpcStatus =
  | 'vivo'
  | 'morto'
  | 'desaparecido'
  | 'enlouquecido'
  | 'convertido'
  | 'outro';

export interface CocStatBlock {
  /** Free markdown stat block. */
  markdown: string;
  /** Optional structured characteristics (CoC 7e). */
  FOR?: number;
  CON?: number;
  TAM?: number;
  DES?: number;
  APA?: number;
  INT?: number;
  POD?: number;
  EDU?: number;
  SAN?: number;
  PV?: number;
  PM?: number;
  Sorte?: number;
  /** Key skills: name -> value. */
  skills?: Array<{ name: string; value: number }>;
}

export interface ScheduleEntry {
  period: DayPeriod;
  locationId: Uuid;
  activity: string;
}

/** A plot-specific layer attached to an NPC (section 4 + 5.2). */
export interface NpcPlotLayer {
  plotId: Uuid;
  knows: string;
  hides: string;
  revealsIfPressed: string;
  activationCondition?: ActivationCondition;
}

export interface NpcEntity extends BaseEntity, ImportableFields {
  name: string;
  portraitBlobId?: Uuid;
  appearance: string;
  voiceAndMannerisms: string;
  typicalLines: string[];
  factionIds: Uuid[];
  statBlock: CocStatBlock;
  schedule: ScheduleEntry[];
  status: NpcStatus;
  isKnownToPlayers: boolean;
  layers: NpcPlotLayer[];
}

/* ------------------------------------------------------------------ Faction */

export interface FactionPlotLayer {
  plotId: Uuid;
  whatChanges: string;
  activationCondition?: ActivationCondition;
}

export interface FactionEntity extends BaseEntity, ImportableFields {
  name: string;
  goals: string;
  resources: string;
  memberNpcIds: Uuid[];
  locationIds: Uuid[];
  symbol?: string;
  layers: FactionPlotLayer[];
}

/* ------------------------------------------------------------------ Plot */

export type PlotState = 'dormente' | 'ativa' | 'escalando' | 'resolvida' | 'fracassada';

export interface Beat {
  /** Clock segment at which this beat is suggested. */
  atSegment: number;
  title: string;
  description: string;
  effects: Effect[];
}

export interface Conclusion {
  id: Uuid;
  title: string;
  description: string;
}

export interface PlotClock {
  /** 4, 6, 8 or 12. */
  segments: number;
  filled: number;
  advanceRules: string[];
}

export interface PlotEntity extends BaseEntity {
  name: string;
  /** Free text, e.g. the published scenario name. */
  sourceModule: string;
  threatLevel: number;
  hiddenTruth: string;
  antagonists: string;
  state: PlotState;
  activationTrigger?: string;
  clock: PlotClock;
  scheduledBeats: Beat[];
  conclusions: Conclusion[];
}

/* ------------------------------------------------------------------ Activation conditions (5.2) */

export type ActivationLeaf =
  | { kind: 'plotState'; plotId: Uuid; op: 'is' | 'isNot'; value: PlotState }
  | { kind: 'plotClockFilled'; plotId: Uuid; op: 'gte'; value: number }
  | { kind: 'clueStatus'; clueId: Uuid; op: 'is'; value: ClueStatus }
  | { kind: 'npcStatus'; npcId: Uuid; op: 'is'; value: NpcStatus }
  | { kind: 'locationDiscovered'; locationId: Uuid; value: boolean };

export type ActivationCondition =
  | { kind: 'always' }
  | ActivationLeaf
  | { kind: 'all'; conditions: ActivationCondition[] } // AND (E)
  | { kind: 'any'; conditions: ActivationCondition[] }; // OR (OU)

/* ------------------------------------------------------------------ Location plot layer */

export interface LocationPlotLayer extends BaseEntity {
  locationId: Uuid;
  plotId: Uuid;
  whatChanges: string;
  readAloudOverride?: string;
  readAloudAppend?: string;
  cluesHere: Uuid[];
  sceneCardIds: Uuid[];
  activationCondition: ActivationCondition;
}

/* ------------------------------------------------------------------ Scene card */

export interface SceneOutcome {
  label: string;
  description: string;
  nextSceneCardId?: Uuid;
  nextLocationId?: Uuid;
  effects: Effect[];
}

export interface SceneCardEntity extends BaseEntity, ImportableFields {
  title: string;
  plotId: Uuid;
  locationId?: Uuid;
  trigger: string;
  /** Read-aloud opening text. */
  openingText: string;
  whatHappens: string;
  outcomes: SceneOutcome[];
  repeatable: boolean;
  used: boolean;
}

/* ------------------------------------------------------------------ Clue */

export type ClueStatus = 'nao-descoberta' | 'descoberta' | 'perdida';
export type CocDifficulty = 'Regular' | 'Dificil' | 'Extremo';

export interface ClueEntity extends BaseEntity, ImportableFields {
  text: string;
  plotIds: Uuid[];
  locationId?: Uuid;
  npcId?: Uuid;
  howToObtain: { method: string; difficulty?: CocDifficulty };
  revealsConclusionId?: Uuid;
  pointsToPlotIds: Uuid[];
  /** A clue that links two plots (bridge). */
  isBridge: boolean;
  handoutIds: Uuid[];
  status: ClueStatus;
  discoveredInEventId?: Uuid;
}

/* ------------------------------------------------------------------ Handout */

export interface HandoutDelivery {
  tableId: Uuid;
  deliveredAt: IsoDateTime;
  note: string;
}

export interface HandoutEntity extends BaseEntity, ImportableFields {
  title: string;
  /** Image/PDF blob reference, OR plain text content. */
  fileBlobId?: Uuid;
  textContent?: string;
  clueId?: Uuid;
  locationId?: Uuid;
  deliveries: HandoutDelivery[];
  playerSafeCaption: string;
}

/* ------------------------------------------------------------------ Table / Session */

export interface TableEntity extends BaseEntity {
  name: string;
  players: Array<{ name: string; characterName: string }>;
  inGameDate: string;
  partyLocationId?: Uuid;
}

export interface SessionEntity extends BaseEntity {
  tableId: Uuid;
  realDate: string;
  inGameStart: string;
  inGameEnd: string;
  summary: string;
  eventIds: Uuid[];
}

/* ------------------------------------------------------------------ Investigator */

export interface InvestigatorLink {
  targetType: 'location' | 'npc' | 'faction' | 'plot';
  targetId: Uuid;
  note: string;
}

export interface InvestigatorEntity extends BaseEntity {
  name: string;
  playerName: string;
  tableId: Uuid;
  portraitBlobId?: Uuid;
  concept: string;
  occupation: string;
  age: number;
  characteristics: {
    FOR: number;
    CON: number;
    TAM: number;
    DES: number;
    APA: number;
    INT: number;
    POD: number;
    EDU: number;
  };
  derived: {
    PV: number;
    PM: number;
    SAN: number;
    Sorte: number;
    Movimento: number;
    Corpo: string; // build / "Corpo" in pt-BR
    BonusDeDano: string;
  };
  skills: Array<{ name: string; value: number }>;
  backstory: string;
  equipment: string;
  hook: string;
  links: InvestigatorLink[];
  status: string;
  masterNotes: string;
}

/* ------------------------------------------------------------------ Session Zero (13) */

export type LoreScope = 'epoca' | 'cidade' | 'cultura' | 'faccao';

export interface SessionZeroEntity extends BaseEntity {
  tableId: Uuid;
  agenda: Array<{ title: string; estimatedMinutes: number; notes: string; done: boolean }>;
  tone: { lines: string; veils: string; xCard: boolean; horrorLevel: string; notes: string };
  houseRules: Array<{ text: string; active: boolean }>;
  loreCards: Array<{ title: string; scope: LoreScope; readAloud: string; masterNotes: string }>;
  rumors: Array<{ text: string; plotId?: Uuid; clueId?: Uuid; toldToTableIds: Uuid[] }>;
}

/* ------------------------------------------------------------------ Event (journal) */

export type EventType =
  | 'descoberta'
  | 'morte'
  | 'avanco-de-relogio'
  | 'mudanca-de-estado'
  | 'nota'
  | 'entrega-de-handout'
  | 'outro';

export interface EventEntity extends BaseEntity {
  inGameDate: string;
  tableId?: Uuid;
  type: EventType;
  text: string;
  linkedEntityIds: Uuid[];
  effectsApplied: Effect[];
}

/* ------------------------------------------------------------------ Effects */

export type Effect =
  | { type: 'setClueStatus'; clueId: Uuid; status: ClueStatus }
  | { type: 'setNpcStatus'; npcId: Uuid; status: NpcStatus }
  | { type: 'moveNpc'; npcId: Uuid; locationId: Uuid }
  | { type: 'advanceClock'; plotId: Uuid; by: number }
  | { type: 'setPlotState'; plotId: Uuid; state: PlotState }
  | { type: 'markLocationDiscovered'; locationId: Uuid }
  | { type: 'markHandoutDelivered'; handoutId: Uuid; tableId: Uuid }
  | { type: 'markSceneUsed'; sceneCardId: Uuid };

/* ------------------------------------------------------------------ Import batch */

export interface ImportBatchEntity {
  id: Uuid;
  mode: 'cidade' | 'cenario';
  label: string;
  createdAt: IsoDateTime;
  createdIds: Array<{ table: StoreName; id: Uuid }>;
  /** Snapshot of records that were updated, keyed for undo. */
  snapshotOfUpdated: Array<{ table: StoreName; id: Uuid; before: unknown }>;
  status: 'applied' | 'undone';
}

/* ------------------------------------------------------------------ Blobs / meta */

export interface BlobRecord {
  id: Uuid;
  /** MIME type. */
  type: string;
  data: Blob;
}

export interface MetaRecord {
  key: string;
  value: unknown;
}

